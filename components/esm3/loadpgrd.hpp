#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

#include <components/esm/defs.hpp>
#include <components/esm/refid.hpp>

namespace ESM
{

    class ESMReader;
    class ESMWriter;

    /*
     * Path grid.
     */
    struct Pathgrid
    {
        constexpr static RecNameInts sRecordId = REC_PGRD;

        /// Return a string descriptor for this record type. Currently used for debugging / error logs only.
        static std::string_view getRecordType() { return "Pathgrid"; }

        struct DATAstruct
        {
            std::int32_t mX, mY; // Grid location, matches cell for exterior cells
            std::int16_t mGranularity; // Granularity with which the graph was autogenerated
            std::uint16_t mPoints; // Number of path points.
        }; // 12 bytes

        struct Point // path grid point
        {
            std::int32_t mX, mY, mZ; // Location of point
            std::uint8_t mAutogenerated; // autogenerated vs. user coloring flag?
            std::uint8_t mConnectionNum; // number of connections for this point
            Point& operator=(const float[3]);
            explicit Point(const float[3]);
            Point();
            Point(std::int32_t x, std::int32_t y, std::int32_t z)
                : mX(x)
                , mY(y)
                , mZ(z)
                , mAutogenerated(0)
                , mConnectionNum(0)
            {
            }
        }; // 16 bytes

        struct Edge // path grid edge
        {
            std::size_t mV0, mV1; // index of points connected with this edge
        };

        ESM::RefId mCell; // Cell name
        DATAstruct mData{};

        typedef std::vector<Point> PointList;
        PointList mPoints;

        typedef std::vector<Edge> EdgeList;
        EdgeList mEdges;

        void load(ESMReader& esm, bool& isDeleted);
        void save(ESMWriter& esm, bool isDeleted = false) const;

        void blank();
    };
}
