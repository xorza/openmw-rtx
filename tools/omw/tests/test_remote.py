class LibrariesTest(unittest.TestCase):
    def test_the_libraries_the_other_machine_lacks_are_the_linked_ones_it_names_no_soname_of(self):
        offered = sonames(
            "1234 libs found in cache `/etc/ld.so.cache'\n"
            "\tlibz.so.1 (libc6,x86-64) => /usr/lib/libz.so.1\n"
            "\tlibvulkan.so.1 (libc6,x86-64) => /usr/lib/libvulkan.so.1\n"
            "Cache generated by: ldconfig (GNU libc) release version 2.43\n")
        self.assertEqual(offered, {"libz.so.1", "libvulkan.so.1"})

        # The vDSO, the loader and a library that did not resolve name no file to copy; a library
        # listed twice, by the binary and by a plugin, is one.
        libraries = linked(
            "/build/openmw-rtxtool:\n"
            "\tlinux-vdso.so.1 (0x00007ffd)\n"
            "\tlibz.so.1 => /lib/x86_64-linux-gnu/libz.so.1 (0x00007f00)\n"
            "\tlibosg.so.162 => /lib/x86_64-linux-gnu/libosg.so.162 (0x00007f01)\n"
            "\tlibgone.so.3 => not found\n"
            "\t/lib64/ld-linux-x86-64.so.2 (0x00007f02)\n"
            "/osgPlugins-3.6.5/osgdb_png.so:\n"
            "\tlibosg.so.162 => /lib/x86_64-linux-gnu/libosg.so.162 (0x00007f01)\n"
            "\tlibpng16.so.16 => /lib/x86_64-linux-gnu/libpng16.so.16 (0x00007f03)\n")
        self.assertEqual(libraries, {
            "libz.so.1": "/lib/x86_64-linux-gnu/libz.so.1",
            "libosg.so.162": "/lib/x86_64-linux-gnu/libosg.so.162",
            "libpng16.so.16": "/lib/x86_64-linux-gnu/libpng16.so.16",
        })
        self.assertEqual(list(lacking(libraries, offered)), ["libosg.so.162", "libpng16.so.16"])


@unittest.skipIf(WINDOWS, "remote is Linux's")
class BuildFolderTest(unittest.TestCase):
    def test_a_host_that_does_not_answer_is_told_from_a_folder_it_cannot_write(self):
        parent = Path("/home/user/Projects/openmw")
        self.assertIsNone(build_refusal("user@host", parent, 0))
        self.assertEqual(build_refusal("user@host", parent, 255),
                         "remote: ssh reached no shell on user@host, as it says above")
        self.assertEqual(build_refusal("user@host", parent, 1),
                         "user@host cannot write /home/user/Projects/openmw, where the build goes: make it once there "
                         "with `sudo mkdir -p /home/user/Projects/openmw && "
                         "sudo chown $USER: /home/user/Projects/openmw`")

    def test_the_folders_the_outputs_come_back_into_are_made_before_the_run_and_one_that_cannot_be_is_refused(self):
        with tempfile.TemporaryDirectory() as scratch:
            root = Path(scratch)
            make_parents([root / "a" / "b" / "tour", root / "c" / "shot.png", root / "flat"])
            self.assertTrue((root / "a" / "b").is_dir())
            self.assertTrue((root / "c").is_dir())
            self.assertFalse((root / "a" / "b" / "tour").exists(), "the output itself is the run's to write")
            (root / "file").write_text("")
            with self.assertRaisesRegex(Refusal, "where tour comes back to, cannot be made here"):
                make_parents([root / "file" / "deeper" / "tour"])

    def test_a_file_the_run_did_not_write_is_told_from_a_copy_that_failed(self):
        self.assertEqual(fetch_note(0), "")
        self.assertEqual(fetch_note(23), " was not written there")
        self.assertEqual(fetch_note(255), " could not be brought back: rsync exited 255")
        self.assertEqual(fetch_note(12), " could not be brought back: rsync exited 12")


# The two machines' paths are one Linux path, and `remote` refuses on Windows: there `Path` spells
# them with backslashes, as no machine the line goes to reads them.
@unittest.skipIf(WINDOWS, "remote is Linux's")
class RemoteLineTest(unittest.TestCase):
    def test_a_path_the_run_writes_or_reads_is_made_absolute_in_either_form(self):
        here = Path("/desk/tree")
        line = remote_line(["--views=ship", "--json", "out.json", "--frame-times=/abs/times", "--against=base",
                            "--window=true"], "bench", here)
        self.assertEqual(line.args, ["--views=ship", "--json=/desk/tree/out.json", "--frame-times=/abs/times",
                                     "--against=/desk/tree/base", "--window=true"])
        self.assertEqual(line.outputs, [Path("/desk/tree/out.json"), Path("/abs/times")])
        self.assertEqual(line.inputs, [Path("/desk/tree/base")])

    def test_a_bench_with_nothing_said_of_a_window_runs_without_one_and_nothing_else_is_told(self):
        self.assertEqual(remote_line(["--views=ship"], "bench", Path("/")).args, ["--views=ship", "--window=false"])
        self.assertEqual(remote_line(["--window", "--views=ship"], "bench", Path("/")).args,
                         ["--window", "--views=ship"])
        self.assertEqual(remote_line(["--views=ship"], "shot", Path("/")).args, ["--views=ship"])

    def test_a_path_is_made_absolute_without_reading_the_links_of_this_machine(self):
        self.assertEqual(remote_line(["--keys=../keys.txt"], "film", Path("/desk/tree/sub")).inputs,
                         [Path("/desk/tree/keys.txt")])

    def test_a_switch_that_names_no_path_or_a_path_only_this_machine_has_is_refused(self):
        for line in (["--json"], ["--perf-control=/tmp/fifo"]):
            with self.subTest(line=line), self.assertRaises(Refusal):
                remote_line(line, "bench", Path("/"))


@unittest.skipIf(WINDOWS, "remote is Linux's")
class RemoteScriptTest(unittest.TestCase):
    def test_the_run_is_the_harness_under_its_libraries_and_a_measured_one_holds_the_clock(self):
        folder = Path("/home/me/tree/out/release")
        script = remote_script(folder, "bench", ["--views=a b"], measured=True)
        lines = script.splitlines()
        self.assertEqual(lines[1], "cd /home/me/tree/out/release")
        self.assertIn("LD_LIBRARY_PATH=/home/me/tree/out/release/remote-lib", lines[2])
        self.assertIn("WAYLAND_DISPLAY=wayland-0 SDL_VIDEO_DRIVER=wayland", lines[3])
        self.assertIn("else export SDL_VIDEO_DRIVER=offscreen", lines[3])
        self.assertEqual(lines[-1], "./openmw-rtxtool bench '--views=a b'")
        self.assertIn("GpuPerformanceLevel s manual", script)
        # Put back on the way out, which an exec would never reach.
        self.assertIn("trap 'gpu set-property GpuPerformanceLevel s \"$level\"; [ \"$level\" = manual ]", script)
        self.assertNotIn("exec ", script)

        unmeasured = remote_script(folder, "shot", [], measured=False)
        self.assertNotIn("steamos", unmeasured.lower())
        self.assertEqual(unmeasured.splitlines()[-1], "./openmw-rtxtool shot")


class EnvironmentTest(unittest.TestCase):
    def test_the_environment_ahead_of_the_verb_is_split_off_in_either_form_and_a_bad_word_refused(self):
        split = split_env(["--env", "GLIBC_TUNABLES=glibc.malloc.mmap_threshold=262144", "--env=A=", "tour", "--env=x"])
        self.assertEqual(split.env, [("GLIBC_TUNABLES", "glibc.malloc.mmap_threshold=262144"), ("A", "")])
        self.assertEqual(split.words, ["tour", "--env=x"])
        self.assertEqual(split_env(["bench"]), EnvSplit(env=[], words=["bench"]))
        for bad in (["--env"], ["--env", "NOVALUE", "tour"], ["--env", "1A=b", "tour"], ["--env", "A-B=c", "tour"]):
            with self.subTest(bad=bad), self.assertRaises(Refusal):
                split_env(bad)

    @unittest.skipIf(WINDOWS, "remote is the desk's")
    def test_a_linux_run_exports_the_environment_quoted(self):
        script = remote_script(Path("/t/out/release"), "tour", [], measured=False, env=[("A", "x y"), ("B", "")])
        self.assertIn("export A='x y'", script.splitlines())
        self.assertIn("export B=''", script.splitlines())


class WindowsHostTest(unittest.TestCase):
    def test_cmd_echoes_windows_and_a_posix_shell_echoes_the_word(self):
        self.assertTrue(is_windows("Windows_NT\r\n"))
        self.assertFalse(is_windows("%OS%\n"))
        self.assertFalse(is_windows(""))

    def test_a_word_is_quoted_only_where_cmd_would_split_or_read_it(self):
        self.assertEqual(cmd_quote("--frames=200"), "--frames=200")
        self.assertEqual(cmd_quote("C:\\Users\\me\\My Games"), '"C:\\Users\\me\\My Games"')
        self.assertEqual(cmd_quote('a"b'), '"a""b"')
        self.assertEqual(cmd_quote("100%"), '"100%%"')
        self.assertEqual(cmd_quote(""), '""')

    @unittest.skipIf(WINDOWS, "the line's paths are this desk's")
    def test_the_lines_paths_are_mapped_into_the_runs_folder_and_the_script_ends_in_its_status(self):
        run = WindowsRun(PureWindowsPath("C:/Users/me/.cache/omw-remote/abc"))
        out = Path("/home/me/runs/deck/pbr")
        self.assertEqual(windows_args(["--out=/home/me/runs/deck/pbr", "--window=false", "--out-x=/y"], [out], run),
                         ["--out=C:\\Users\\me\\.cache\\omw-remote\\abc\\files\\pbr", "--window=false",
                          "--out-x=/y"])
        script = windows_script(PureWindowsPath("C:/Users/me/Projects/openmw/out/release"), run, "tour",
                                ["--config=C:\\My Games\\pbr"], [("GLIBC_TUNABLES", "x=1")]).split("\r\n")
        self.assertEqual(script[0], "@echo off")
        self.assertEqual(script[1], "cd /d C:\\Users\\me\\Projects\\openmw\\out\\release")
        self.assertEqual(script[2], 'set "GLIBC_TUNABLES=x=1"')
        self.assertEqual(script[3], 'openmw-rtxtool.exe tour "--config=C:\\My Games\\pbr" > '
                                    "C:\\Users\\me\\.cache\\omw-remote\\abc\\log.txt 2>&1")
        self.assertEqual(script[4], "echo %ERRORLEVEL% > C:\\Users\\me\\.cache\\omw-remote\\abc\\done.txt")
        self.assertEqual(script[5], "")

    def test_a_commit_the_clone_holds_is_checked_out_with_no_bundle_and_one_it_lacks_comes_as_one(self):
        # An ancestor of what the clone stands at is held there, and its bundle would be empty, which git refuses.
        class Host:
            host = "win"
            profile = PureWindowsPath("C:/Users/me")

            def __init__(self, held):
                self.held = held
                self.lines = []

            def cmd(self, line):
                self.lines.append(line)
                return "" if "status" in line else "b" * 40

            def call(self, line):
                self.lines.append(line)
                return 0 if self.held else 1

            def put(self, local, remote):
                self.lines.append("put")

        def git(command):
            return "a" * 40 if command == ["rev-parse", "HEAD"] else ""

        tree = PureWindowsPath("C:/Users/me/Projects/openmw")
        holding = Host(held=True)
        with mock.patch.object(remotewindows, "run") as bundled:
            self.assertEqual(remotewindows.bring_commit(holding, tree, git), "a" * 40)
        bundled.assert_not_called()
        self.assertNotIn("put", holding.lines)
        self.assertTrue(holding.lines[-1].endswith(f"git checkout -q --detach {'a' * 40}"))

        lacking = Host(held=False)
        with (mock.patch.object(remotewindows, "run") as bundled,
              mock.patch.object(remotewindows.subprocess, "run", return_value=mock.Mock(returncode=0)),
              mock.patch.object(Path, "unlink")):
            remotewindows.bring_commit(lacking, tree, git)
        bundled.assert_called_once()
        self.assertIn("put", lacking.lines)
        # Forced, as the ref stands at whatever another tree brought last, which need not be an ancestor.
        self.assertTrue(any(line.endswith(" +HEAD:refs/omw/remote") for line in lacking.lines))
        self.assertTrue(lacking.lines[-1].endswith(f"git checkout -q --detach {'a' * 40}"))

    def test_the_task_is_deleted_however_the_wait_ends(self):
        # A task made to run once still fires at the time it names: a run whose wait ran out would otherwise start
        # again there.
        lines = []

        class Host:
            host = "win"
            profile = PureWindowsPath("C:/Users/me")

            def __init__(self, *_):
                pass

            def cmd(self, line):
                lines.append(line)
                return ""

            def call(self, _line):
                return 0

            def exists(self, path):
                return path.name == ".git"

            def write(self, _remote, _text):
                pass

        with (mock.patch.object(remotewindows, "WindowsHost", Host),
              mock.patch.object(remotewindows, "bring_commit", return_value="0" * 40),
              mock.patch.object(remotewindows, "RUN_LIMIT_S", 0),
              mock.patch("builtins.print"),
              self.assertRaises(Refusal)):
            remotewindows.remote_windows("ssh", "scp", "win", "release", "tour", [], [], [], [], lambda _: "")
        self.assertEqual(lines[-1], "schtasks /delete /tn omw-remote /f")
        self.assertIn("schtasks /run /tn omw-remote", lines)

    def test_each_tree_builds_in_a_clone_of_its_folders_name_and_one_the_host_lacks_is_refused(self):
        asked = []

        class Host:
            host = "win"
            profile = PureWindowsPath("C:/Users/me")

            def __init__(self, *_):
                pass

            def exists(self, path):
                asked.append(path)
                return False

        with (mock.patch.object(remotewindows, "WindowsHost", Host),
              mock.patch.object(remotewindows, "ROOT", Path("/home/me/Projects/openmw-base")),
              self.assertRaises(Refusal) as refused):
            remotewindows.remote_windows("ssh", "scp", "win", "release", "bench", [], [], [], [], lambda _: "")
        self.assertEqual(asked, [PureWindowsPath("C:/Users/me/Projects/openmw-base/.git")])
        self.assertIn("C:\\Users\\me\\Projects\\openmw-base", str(refused.exception))


